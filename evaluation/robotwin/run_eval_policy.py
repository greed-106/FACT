#!/usr/bin/env python3
"""Run RoboTwin-Phys's evaluator with FACT-side configuration compatibility.

RoboTwin-Phys's PhysTTT task YAMLs intentionally omit
``random_head_camera_dis`` because the environment defaults that field to zero.
Its evaluator still indexes the field while printing the configuration.  Add
the identical default only while that evaluator is running, so the benchmark
checkout and its YAML files remain unchanged.
"""

from __future__ import annotations

import argparse
import runpy
import sys
import types
from pathlib import Path

import yaml


def _install_robotwin_yaml_compatibility() -> None:
    """Apply evaluator-only defaults to RoboTwin configuration dictionaries.

    The benchmark checkout remains untouched.  These normalizations cover
    values that RoboTwin accepts implicitly but which its evaluator or its
    installed CuRobo version requires explicitly.
    """
    original_load = yaml.load

    def load_with_robotwin_defaults(*args, **kwargs):
        value = original_load(*args, **kwargs)
        if not isinstance(value, dict):
            return value
        randomization = value.get("domain_randomization")
        if isinstance(randomization, dict):
            if "random_head_camera_mode" in randomization and "random_head_camera_dis" not in randomization:
                # The PhysTTT camera-mode branch in Base_Task requires this
                # value to be zero; this is also its legacy default.
                randomization["random_head_camera_dis"] = 0

        # The distributed asset templates keep this optional CuRobo field
        # null.  CuRobo needs an explicit mesh root for URDF-relative mesh
        # references, which is exactly the directory containing the absolute
        # URDF path generated by RoboTwin's setup script.
        kinematics = value.get("robot_cfg", {}).get("kinematics")
        if isinstance(kinematics, dict) and kinematics.get("asset_root_path") is None:
            urdf_path = kinematics.get("urdf_path")
            if isinstance(urdf_path, str) and urdf_path:
                kinematics["asset_root_path"] = str(Path(urdf_path).parent)
        return value

    yaml.load = load_with_robotwin_defaults


def _install_curobo_warp_compatibility() -> None:
    """Bridge CuRobo 0.7.2's old Warp device helper to Warp >= 1.16.

    FastWAM's vendored CuRobo already contains the equivalent source change.
    Keep it local to the FACT-launched evaluator instead of changing the
    benchmark checkout or its uv environment.
    """
    import warp as wp

    if not hasattr(wp, "torch"):
        device_from_torch = getattr(wp, "device_from_torch", None)
        if device_from_torch is None:
            raise RuntimeError("Installed Warp exposes neither warp.torch nor warp.device_from_torch")
        wp.torch = types.SimpleNamespace(device_from_torch=device_from_torch)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("policy_script", type=Path, help="Absolute path to RoboTwin-Phys scripts/eval_policy.py")
    args, policy_args = parser.parse_known_args()
    policy_script = args.policy_script.resolve()
    if not policy_script.is_file():
        parser.error(f"RoboTwin-Phys evaluator not found: {policy_script}")

    _install_robotwin_yaml_compatibility()
    _install_curobo_warp_compatibility()
    sys.path.insert(0, str(policy_script.parent))
    sys.argv = [str(policy_script), *policy_args]
    runpy.run_path(str(policy_script), run_name="__main__")


if __name__ == "__main__":
    main()
